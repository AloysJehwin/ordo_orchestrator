const GLYPHS = new Map<string, boolean[][]>(Object.entries(G).map(([k, v]) => [k, v.split("|").map((row) => [...row].map((ch) => ch === "#"))]));

/** Characters outside the font, spelled with ones inside it. */
export function plain(s: string): string {
  return s
    .replace(/≤/g, "<=")
    .replace(/≥/g, ">=")
    .replace(/[–—]/g, "-")
    .replace(/→/g, "->")
    .replace(/×/g, "x")
    .replace(/²/g, "2")
    .replace(/³/g, "3")
    .replace(/⁻¹/g, "-1")
    .replace(/\u00a0/g, " ")
    .replace(/…/g, "...")
    .toUpperCase()
    // µ upper-cases to the Greek capital mu, α to the capital alpha
    .replace(/\u039c/g, "µ")
    .replace(/\u0391/g, "A");
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** The pixels of one character (row-major), or a question mark for one the font lacks. */
export const glyph = (ch: string): boolean[][] => GLYPHS.get(ch) ?? GLYPHS.get(ch.toUpperCase()) ?? GLYPHS.get("?")!;
